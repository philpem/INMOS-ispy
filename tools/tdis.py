#!/usr/bin/env python3
"""Transputer (T2/T4/T8) disassembler with recursive-descent code/data separation.

The ISpy / mtest targets embed compiled occam as byte blobs generated by the
INMOS `ilist`+`tco2h` toolchain.  Linear disassembly of a blob is unreliable
because the blobs interleave code with constant/process tables; this tool adds a
recursive-descent pass that follows direct branches, calls and `ldpi`+`startp`
process pointers, so data is rendered as `db` instead of being mis-decoded.

Usage:
  tdis.py selftest
      Decode the known-good ISpy bootstrap and check it against its comments.

  tdis.py blobs FILE
      List the tco2h-generated code blobs embedded in a binary (DOS .EXE or ELF).

  tdis.py disasm FILE [--offset N] [--length N] [--origin N]
                      [--recursive] [--seed N ...] [--stats]
      Disassemble bytes from FILE.  With --recursive, start at the entry point,
      follow control flow and process pointers, and render unreachable bytes as
      data.  --stats prints coverage and an opcode histogram.

Instruction set: the INMOS T2/T4/T8 primary set, plus the boot-verified
extended OPRs (mint, stlf, sthf, start) and ldpi.
"""

import argparse
import struct
import sys
from collections import Counter

PRIM = {
    0x0: 'j', 0x1: 'ldlp', 0x2: 'pfix', 0x3: 'ldnl', 0x4: 'ldc',
    0x5: 'ldnlp', 0x6: 'nfix', 0x7: 'ldl', 0x8: 'adc', 0x9: 'call',
    0xA: 'cj', 0xB: 'ajw', 0xC: 'eqc', 0xD: 'stl', 0xE: 'stnl', 0xF: 'opr',
}

OPR_SECONDARY = {
    0x0: 'rev', 0x1: 'lb', 0x2: 'bsub', 0x3: 'endp', 0x4: 'diff',
    0x5: 'add', 0x6: 'gcall', 0x7: 'in', 0x8: 'prod', 0x9: 'gt',
    0xA: 'wsub', 0xB: 'out', 0xC: 'sub', 0xD: 'startp', 0xE: 'outbyte',
    0xF: 'outword',
}

OPR_EXTENDED = {
    0x18: 'stlf', 0x1B: 'ldpi', 0x1C: 'sthf', 0x20: 'ret',
    0x42: 'mint', 0x1FF: 'start',
}


def decode(code, pc):
    """Decode one instruction at pc.

    Returns (length, text, kind, target, operand) where kind is one of
    j/cj/call/endp/gcall/startp/ret/other and target is the absolute branch target
    for j/cj/call.
    """
    start = pc
    operand = 0
    while pc < len(code):
        byte = code[pc]
        pc += 1
        op = byte >> 4
        operand |= byte & 0xF
        if op == 0x2:
            operand <<= 4
        elif op == 0x6:
            operand = (~operand) << 4
        else:
            break
    else:
        return (pc - start, '(truncated)', 'other', None, None)
    val = operand

    kind = 'other'
    target = None
    if op == 0x0:
        kind, target, text = 'j', pc + val, 'j %+d' % val
    elif op == 0xA:
        kind, target, text = 'cj', pc + val, 'cj %+d' % val
    elif op == 0x9:
        kind, target, text = 'call', pc + val, 'call %+d' % val
    elif op == 0xF:
        name = OPR_SECONDARY.get(val) or OPR_EXTENDED.get(val)
        text = 'opr %s' % name if name else 'opr 0x%X' % val
        if val == 0x3:
            kind = 'endp'
        elif val == 0x6:
            kind = 'gcall'
        elif val == 0xD:
            kind = 'startp'
        elif val == 0x20:
            kind = 'ret'
    else:
        text = '%s %d' % (PRIM[op], val)

    return (pc - start, text, kind, target, val)


def disassemble(code, start=0, end=None, origin=0):
    out = []
    pc = start
    end = len(code) if end is None else end
    while pc < end:
        ln, text, kind, target, val = decode(code, pc)
        if ln <= 0:
            break
        out.append((pc + origin, text, code[pc:pc + ln], 'code'))
        pc += ln
    return out


def walk(code, seeds):
    """Recursive descent.  Returns (starts, order, seen)."""
    starts, order, seen = set(), [], set()
    work = list(seeds)
    while work:
        pc = work.pop()
        while 0 <= pc < len(code) and pc not in starts:
            if pc in seen:
                break
            starts.add(pc)
            order.append(pc)
            ln, text, kind, target, val = decode(code, pc)
            for k in range(ln):
                if pc + k < len(code):
                    seen.add(pc + k)
            nxt = pc + ln
            if kind == 'j':
                if target is not None:
                    work.append(target)
                break
            if kind in ('cj', 'call'):
                if target is not None:
                    work.append(target)
                pc = nxt
                continue
            if kind in ('endp', 'gcall', 'ret'):
                break
            pc = nxt
    return starts, order, seen


def codepointer_seeds(code, starts):
    seeds = []
    for pc in sorted(starts):
        ln, text, kind, target, val = decode(code, pc)
        if text.startswith('ldc '):
            nxt = pc + ln
            if nxt in starts:
                ln2, t2, k2, g2, v2 = decode(code, nxt)
                if t2 == 'opr ldpi':
                    pointer = nxt + ln2 + val
                    if 0 <= pointer < len(code):
                        seeds.append(pointer)
    return seeds


def analyse(code, seeds=()):
    """Recursive descent with ldpi process-pointer seeding, to a fixpoint."""
    seeds = [0] + [s for s in seeds if 0 <= s < len(code)]
    for _ in range(16):
        starts, order, seen = walk(code, seeds)
        extra = [s for s in codepointer_seeds(code, starts) if s not in starts]
        if not extra:
            break
        seeds += extra
    starts, order, seen = walk(code, seeds)
    return starts, order, seen


def render(code, starts, origin=0):
    out = []
    pc = 0
    while pc < len(code):
        if pc in starts:
            ln, text, kind, target, val = decode(code, pc)
            out.append((pc + origin, text, code[pc:pc + ln], 'code'))
            pc += ln
        else:
            j = pc
            while j < len(code) and j not in starts:
                j += 1
            out.append((pc + origin, None, code[pc:j], 'data'))
            pc = j
    return out


def _long_offsets(mode_off, data, long_size):
    off = mode_off + 10
    if long_size == 8:
        off += (-off) % 8
    if off + 4 * long_size + 8 > len(data):
        return None
    code_size = struct.unpack_from('<%s' % {4: 'i', 8: 'q'}[long_size], data, off)[0]
    meta = off + 4 * long_size
    if long_size == 4:
        bpw, total = struct.unpack_from('<HH', data, meta)
    else:
        bpw, total = struct.unpack_from('<ii', data, meta)
    code_start = mode_off - 10 - code_size
    if code_size <= 0 or code_start < 0 or code_start + code_size > len(data):
        return None
    if bpw not in (2, 4) or total <= 0:
        return None
    return code_start, code_size, bpw, total


def find_blobs(data):
    """Find tco2h-generated code structs, handling 32-bit and 64-bit `long`."""
    blobs = []
    seen_offsets = set()
    i = 0
    while True:
        m = data.find(b'Undefined\x00', i)
        if m < 0:
            break
        i = m + 1
        for long_size in (4, 8):
            r = _long_offsets(m, data, long_size)
            if r and r[0] not in seen_offsets:
                seen_offsets.add(r[0])
                blobs.append({
                    'offset': r[0], 'codesize': r[1], 'bpw': r[2], 'total': r[3],
                    'target': data[m - 10:m].split(b'\x00')[0].decode('latin1'),
                    'code': data[r[0]:r[0] + r[1]],
                })
    return sorted(blobs, key=lambda b: b['offset'])


def _read(path, offset=0, length=None):
    with open(path, 'rb') as f:
        data = f.read()
    end = len(data) if length is None else offset + length
    return data[offset:end]


def cmd_selftest(args):
    boot = bytes.fromhex('B1D124F221FC24F221F8F0605C2A2A2A4AFF212FFF')
    expected = ['ajw 1', 'stl 1', 'opr mint', 'opr sthf', 'opr mint', 'opr stlf',
                'opr rev', 'ldnlp -4', 'ldc 43690', 'opr outword', 'opr start']
    got = [t for _, t, _, _, _ in [decode(boot, p) for p in _pcs(boot)]]
    for g, e in zip(got, expected):
        status = 'ok' if g == e else 'MISMATCH (expected %s)' % e
        print('%-20s %s' % (g, status))
    return 0 if got == expected else 1


def _pcs(code):
    pcs, pc = [], 0
    while pc < len(code):
        pcs.append(pc)
        ln, _, _, _, _ = decode(code, pc)
        if ln <= 0:
            break
        pc += ln
    return pcs


def cmd_blobs(args):
    blobs = find_blobs(_read(args.file))
    for b in blobs:
        print('0x%08X  Code[%d]  bpw=%d  total=%d  target=%r'
              % (b['offset'], b['codesize'], b['bpw'], b['total'], b['target']))
    return 0


def cmd_disasm(args):
    code = _read(args.file, args.offset, args.length)
    if args.recursive:
        starts, order, seen = analyse(code, args.seed)
        rows = render(code, starts, args.origin)
    else:
        rows = disassemble(code, origin=args.origin)

    for pc, text, raw, kind in rows:
        if kind == 'data':
            print('%08X  db %s' % (pc, raw.hex()))
        else:
            print('%08X  %-24s ; %s' % (pc, text, raw.hex()))

    if args.stats:
        starts, order, seen = analyse(code, args.seed)
        hist = Counter(decode(code, p)[1].split()[0] for p in order)
        print('', file=sys.stderr)
        print('bytes:   %d total, %d reachable code (%.0f%%)'
              % (len(code), len(seen), 100.0 * len(seen) / max(1, len(code))), file=sys.stderr)
        print('insns:   %d' % len(order), file=sys.stderr)
        print('opcodes: %s' % hist.most_common(), file=sys.stderr)
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description='Transputer disassembler / recursive-descent analyser')
    sub = p.add_subparsers(dest='cmd', required=True)

    sp = sub.add_parser('selftest', help='validate the decoder against the known bootstrap')
    sp.set_defaults(func=cmd_selftest)

    sp = sub.add_parser('blobs', help='list embedded tco2h code blobs in a binary')
    sp.add_argument('file')
    sp.set_defaults(func=cmd_blobs)

    sp = sub.add_parser('disasm', help='disassemble bytes')
    sp.add_argument('file')
    sp.add_argument('--offset', type=lambda s: int(s, 0), default=0)
    sp.add_argument('--length', type=lambda s: int(s, 0), default=None)
    sp.add_argument('--origin', type=lambda s: int(s, 0), default=0)
    sp.add_argument('--recursive', action='store_true',
                    help='recursive descent; render unreachable bytes as data')
    sp.add_argument('--seed', type=lambda s: int(s, 0), action='append', default=[],
                    help='extra entry point (repeatable)')
    sp.add_argument('--stats', action='store_true', help='coverage and opcode histogram')
    sp.set_defaults(func=cmd_disasm)

    args = p.parse_args(argv)
    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
